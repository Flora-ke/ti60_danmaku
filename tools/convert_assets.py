#!/usr/bin/env python3
"""Convert the six selected UET PNG sources into embedded RGB565 C arrays.

Offline dependency: Pillow (tested with 12.3.0, HPND license).
The target executable needs neither Python nor any image decoder.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct

from PIL import Image, __version__ as pillow_version

ROOT = Path(__file__).resolve().parents[1]
COLOR_KEY = 0xF81F


def crop_checked(image, box):
    x0, y0, x1, y1 = box
    if not (0 <= x0 < x1 <= image.width and 0 <= y0 < y1 <= image.height):
        raise ValueError(f"Crop {box} exceeds source {image.size}")
    return image.crop(box)


def encode(image, transparent):
    values = []
    opaque = collisions = 0
    rgba = image.convert("RGBA")
    pixels = rgba.get_flattened_data() if hasattr(rgba, "get_flattened_data") else rgba.getdata()
    for r, g, b, a in pixels:
        if transparent and a < 128:
            values.append(COLOR_KEY)
            continue
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        # Preserve opaque magenta by changing the blue component by one step.
        if value == COLOR_KEY:
            value = COLOR_KEY - 1
            collisions += 1
        values.append(value)
        opaque += 1
    if not opaque:
        raise ValueError("Sprite is completely transparent")
    payload = struct.pack("<" + "H" * len(values), *values)
    return values, opaque, collisions, payload


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path,
                        help="Original UET_Danmaku assets directory")
    parser.add_argument("--output-root", type=Path, default=ROOT)
    args = parser.parse_args()
    source = args.source.resolve()
    # (C name, source filename, safe crop, output size, transparency)
    specs = [
        ("background", "background.png", None, (400, 300), False),
        ("player_idle", "reimu.png", (0, 0, 32, 48), (16, 24), True),
        ("player_left", "reimu.png", (0, 48, 32, 96), (16, 24), True),
        ("player_right", "reimu.png", (0, 96, 32, 144), (16, 24), True),
        ("boss", "flan.png", (0, 0, 43, 69), (21, 34), True),
        ("bullet_ring", "flanBullet.png", (0, 0, 16, 16), (8, 8), True),
        ("bullet_sweep", "flanbullet2.png", (0, 0, 10, 17), (10, 17), True),
        ("shot", "playerbullet.png", (0, 0, 21, 23), (6, 7), True),
    ]
    result = ["/* Generated by tools/convert_assets.py; do not edit by hand. */",
              '#include "assets.h"', ""]
    entries = []
    total = 0
    for name, filename, box, size, transparent in specs:
        source_bytes = (source / filename).read_bytes()
        with Image.open(source / filename) as original:
            original_size = original.size
            rgba = original.convert("RGBA")
        cropped = crop_checked(rgba, box) if box else rgba
        image = cropped.resize(size, Image.Resampling.NEAREST)
        values, opaque, collisions, payload = encode(image, transparent)
        result.append(f"static const uint16_t pixels_{name}[{len(values)}] = {{")
        for pos in range(0, len(values), 12):
            result.append("    " + ", ".join(f"0x{v:04X}" for v in values[pos:pos + 12]) + ",")
        result.extend(["};", ""])
        entries.append({
            "symbol": "asset_" + name,
            "source": "assets/" + filename,
            "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
            "source_dimensions": list(original_size),
            "crop_xyxy": list(box) if box else [0, 0, *original_size],
            "width": size[0], "height": size[1],
            "binary_bytes": len(payload),
            "sha256_rgb565_le": hashlib.sha256(payload).hexdigest(),
            "opaque_pixels": opaque, "transparent_pixels": len(values) - opaque,
            "opaque_key_collisions_replaced": collisions,
            "uses_color_key": transparent,
        })
        total += len(payload)
    for name, _, _, size, _ in specs:
        if not name.startswith("player_"):
            result.append(f"const GameSprite asset_{name} = {{{size[0]}, {size[1]}, pixels_{name}}};")
    result.extend(["const GameSprite asset_player[3] = {",
                   "    {16, 24, pixels_player_idle},",
                   "    {16, 24, pixels_player_left},",
                   "    {16, 24, pixels_player_right}", "};", ""])
    out = args.output_root.resolve() / "assets"
    out.mkdir(parents=True, exist_ok=True)
    (out / "assets.c").write_text("\n".join(result), encoding="utf-8", newline="\n")
    manifest = {
        "source_project": "https://github.com/cusnaruto/UET_Danmaku",
        "scope": "Selected visual assets only; no music, font, SDL dependency on target",
        "generator": "tools/convert_assets.py",
        "offline_dependency": {"name": "Pillow", "version": pillow_version, "license": "HPND"},
        "pixel_format": "RGB565 numeric uint16_t",
        "digest_serialization": "row-major uint16 little-endian, exactly width*height*2 bytes",
        "color_key": "0xF81F",
        "transparency": "For sprites alpha<128 -> color key; alpha>=128 -> opaque RGB565. No blending.",
        "opaque_key_collision_policy": "Replace 0xF81F with 0xF81E",
        "resize": "nearest neighbor",
        "total_pixel_bytes": total,
        "notes": [
            "GameSprite metadata is additional and depends on target pointer size/alignment.",
            "Source reimu.png is 256x144: use exact 32x48 cells rather than original invalid 32x49 cells.",
            "Source playerbullet.png is 42x23: use its left 21x23 arrow, not original 24x29 out-of-bounds rect.",
            "asset_player is the public array: idle/left/right correspond to entries player_idle/player_left/player_right.",
        ],
        "assets": entries,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(specs)} images, {total} pixel bytes ({total / 1024:.2f} KiB)")


if __name__ == "__main__":
    main()
